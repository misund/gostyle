package gostyle

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const (
	cleanSrc    = "package a\n\nfunc f(a int) {}\n"
	violatingFn = "func old(a, b int) {}\n"
)

// result is the outcome of one Run invocation.
type result struct {
	code   int
	stdout string
	stderr string
}

// run invokes Run with args.
func run(
	t *testing.T,
	args ...string,
) result {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := Run(
		args,
		&stdout,
		&stderr,
	)

	return result{
		code:   code,
		stdout: stdout.String(),
		stderr: stderr.String(),
	}
}

// writeFiles creates files (relative path to content) below dir.
func writeFiles(
	t *testing.T,
	dir string,
	files map[string]string,
) {
	t.Helper()
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(
			filepath.Dir(path),
			0o755,
		); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(
			path,
			[]byte(content),
			0o644,
		); err != nil {
			t.Fatal(err)
		}
	}
}

// newRepo creates a git repository containing files in one commit, and makes
// it the working directory for the rest of the test.
func newRepo(
	t *testing.T,
	files map[string]string,
) string {
	t.Helper()
	dir, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	runGit(
		t,
		dir,
		"init",
		"-q",
		".",
	)
	writeFiles(
		t,
		dir,
		files,
	)
	runGit(
		t,
		dir,
		"add",
		".",
	)
	runGit(
		t,
		dir,
		"commit",
		"-q",
		"-m",
		"init",
	)

	orig, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := os.Chdir(orig); err != nil {
			t.Errorf("restore working directory: %v", err)
		}
	})

	return dir
}

func readFile(
	t *testing.T,
	path string,
) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	return string(b)
}

func TestRunExitCodes(t *testing.T) {
	dir := t.TempDir()
	writeFiles(
		t,
		dir,
		map[string]string{
			"clean.go":     cleanSrc,
			"violating.go": "package a\n\n" + violatingFn,
			"broken.go":    "package a\n\nfunc (",
		},
	)

	tests := []struct {
		name       string
		args       []string
		wantCode   int
		wantStdout string
		wantStderr string
	}{
		{
			name:     "clean file",
			args:     []string{filepath.Join(dir, "clean.go")},
			wantCode: 0,
		},
		{
			name: "violating file",
			args: []string{filepath.Join(dir, "violating.go")},

			wantCode:   1,
			wantStdout: "violating.go:3:",
		},
		{
			name:       "file that does not parse",
			args:       []string{filepath.Join(dir, "broken.go")},
			wantCode:   2,
			wantStderr: "broken.go",
		},
		{
			name:       "path that does not exist",
			args:       []string{filepath.Join(dir, "missing.go")},
			wantCode:   2,
			wantStderr: "missing.go",
		},
		{
			name:       "unknown flag",
			args:       []string{"-nope"},
			wantCode:   2,
			wantStderr: "flag provided but not defined",
		},
		{
			name:       "version",
			args:       []string{"-version"},
			wantCode:   0,
			wantStdout: "gostyle ",
		},
		{
			name:       "help exits cleanly and prints usage",
			args:       []string{"-h"},
			wantCode:   0,
			wantStderr: "-changed",
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := run(t, tc.args...)
			if got.code != tc.wantCode {
				t.Errorf(
					"exit code: got %d, want %d\nstdout: %s\nstderr: %s",
					got.code,
					tc.wantCode,
					got.stdout,
					got.stderr,
				)
			}
			if !strings.Contains(got.stdout, tc.wantStdout) {
				t.Errorf(
					"stdout %q does not contain %q",
					got.stdout,
					tc.wantStdout,
				)
			}
			if !strings.Contains(got.stderr, tc.wantStderr) {
				t.Errorf(
					"stderr %q does not contain %q",
					got.stderr,
					tc.wantStderr,
				)
			}
		})
	}
}

func TestRunDirectoryWalk(t *testing.T) {
	dir := t.TempDir()
	violating := "package a\n\n" + violatingFn
	writeFiles(
		t,
		dir,
		map[string]string{
			"top.go":                    violating,
			"nested/deep/inner.go":      violating,
			"vendor/v.go":               violating,
			"node_modules/n.go":         violating,
			".hidden/h.go":              violating,
			"generated.go":              "// Code generated by x. DO NOT EDIT.\n\n" + violating,
			"nested/not_go.txt":         "func old(a, b int) {}",
			"nested/deep/inner_test.go": violating,
		},
	)

	for _, suffix := range []string{"", "/", "/..."} {
		t.Run("path suffix "+suffix, func(t *testing.T) {
			got := run(t, dir+suffix)
			if got.code != 1 {
				t.Fatalf(
					"exit code: got %d, want 1\nstderr: %s",
					got.code,
					got.stderr,
				)
			}
			for _, want := range []string{"top.go", "inner.go", "inner_test.go"} {
				if !strings.Contains(got.stdout, want) {
					t.Errorf(
						"want %s reported, got:\n%s",
						want,
						got.stdout,
					)
				}
			}
			for _, skipped := range []string{"v.go", "n.go", "h.go", "generated.go", "not_go.txt"} {
				if strings.Contains(got.stdout, skipped) {
					t.Errorf(
						"want %s skipped, got:\n%s",
						skipped,
						got.stdout,
					)
				}
			}
		})
	}
}

func TestRunDotPath(t *testing.T) {
	newRepo(
		t,
		map[string]string{"a.go": "package a\n\n" + violatingFn},
	)
	for _, arg := range []string{".", "./...", "..."} {
		t.Run(arg, func(t *testing.T) {
			got := run(t, arg)
			if got.code != 1 || !strings.Contains(got.stdout, "a.go:3:") {
				t.Fatalf("got %+v", got)
			}
		})
	}
}

func TestRunWidth(t *testing.T) {
	dir := t.TempDir()
	src := "package a\n\n" +
		"func g(\n\ta,\n\tb string,\n) {\n}\n\n" +
		"func f() {\n\tg(\"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\", \"bbbbbbbbbbbbbbbbbbbbbbbbb\")\n}\n"
	writeFiles(
		t,
		dir,
		map[string]string{"a.go": src},
	)
	path := filepath.Join(dir, "a.go")

	if got := run(t, path); got.code != 0 {
		t.Errorf("default width: got %+v, want clean", got)
	}
	got := run(
		t,
		"-width",
		"60",
		path,
	)
	if got.code != 1 || !strings.Contains(got.stdout, "exceeds 60 columns") {
		t.Errorf("-width 60: got %+v, want an over-width violation", got)
	}
	if got := run(
		t,
		"-tab",
		"16",
		path,
	); got.code != 1 {
		t.Errorf("-tab 16: got %+v, want the tab width to count", got)
	}
}

func TestRunFix(t *testing.T) {
	dir := t.TempDir()
	writeFiles(
		t,
		dir,
		map[string]string{
			"a.go":      "package a\n\n" + violatingFn,
			"broken.go": "package a\n\nfunc (",
		},
	)
	path := filepath.Join(dir, "a.go")

	got := run(
		t,
		"-fix",
		path,
	)
	if got.code != 0 || got.stdout != "" {
		t.Fatalf("-fix: got %+v, want clean", got)
	}
	want := "package a\n\nfunc old(\n\ta,\n\tb int,\n) {\n}\n"
	if content := readFile(t, path); content != want {
		t.Errorf(
			"fixed file:\n%s\nwant:\n%s",
			content,
			want,
		)
	}

	broken := filepath.Join(dir, "broken.go")
	if got := run(
		t,
		"-fix",
		broken,
	); got.code != 2 {
		t.Errorf(
			"-fix on a file that does not parse: got %+v, want exit 2",
			got,
		)
	}
	if content := readFile(t, broken); content != "package a\n\nfunc (" {
		t.Errorf("file that does not parse was modified: %q", content)
	}
}

func TestRunChanged(t *testing.T) {
	newFn := "\nfunc added(c, d int) {}\n"

	t.Run("reports only changed lines", func(t *testing.T) {
		dir := newRepo(
			t,
			map[string]string{"a.go": "package a\n\n" + violatingFn},
		)
		path := filepath.Join(dir, "a.go")

		// Nothing changed yet: the old violation is not reported.
		if got := run(t, "-changed"); got.code != 0 || got.stdout != "" {
			t.Fatalf("unchanged tree: got %+v, want clean", got)
		}

		writeFiles(
			t,
			dir,
			map[string]string{"a.go": readFile(t, path) + newFn},
		)
		got := run(t, "-changed")
		if got.code != 1 {
			t.Fatalf("got %+v, want exit 1", got)
		}
		if !strings.Contains(got.stdout, "a.go:5:") {
			t.Errorf(
				"want the added function (line 5) reported, got:\n%s",
				got.stdout,
			)
		}
		if strings.Contains(got.stdout, "a.go:3:") {
			t.Errorf(
				"want the untouched function (line 3) skipped, got:\n%s",
				got.stdout,
			)
		}
	})

	t.Run("untracked files count as fully changed", func(t *testing.T) {
		dir := newRepo(
			t,
			map[string]string{"a.go": cleanSrc},
		)
		writeFiles(
			t,
			dir,
			map[string]string{"new.go": "package a\n\n" + violatingFn},
		)
		got := run(t, "-changed")
		if got.code != 1 || !strings.Contains(got.stdout, "new.go:3:") {
			t.Fatalf("got %+v", got)
		}
	})

	t.Run("fix touches only changed lines", func(t *testing.T) {
		dir := newRepo(
			t,
			map[string]string{"a.go": "package a\n\n" + violatingFn},
		)
		path := filepath.Join(dir, "a.go")
		writeFiles(
			t,
			dir,
			map[string]string{"a.go": readFile(t, path) + newFn},
		)

		got := run(
			t,
			"-fix",
			"-changed",
		)
		if got.code != 0 || got.stdout != "" {
			t.Fatalf("got %+v, want clean", got)
		}
		content := readFile(t, path)
		if !strings.Contains(content, violatingFn) {
			t.Errorf("untouched function was rewritten:\n%s", content)
		}
		if !strings.Contains(content, "func added(\n\tc,\n\td int,\n) {\n}") {
			t.Errorf("added function was not fixed:\n%s", content)
		}
	})

	t.Run("explicit path still filters to changed lines", func(t *testing.T) {
		dir := newRepo(
			t,
			map[string]string{"a.go": "package a\n\n" + violatingFn},
		)
		got := run(
			t,
			"-changed",
			filepath.Join(dir, "a.go"),
		)
		if got.code != 0 {
			t.Fatalf("got %+v, want clean", got)
		}
	})

	t.Run("outside a git repository", func(t *testing.T) {
		dir := t.TempDir()
		orig, err := os.Getwd()
		if err != nil {
			t.Fatal(err)
		}
		if err := os.Chdir(dir); err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() {
			if err := os.Chdir(orig); err != nil {
				t.Errorf("restore working directory: %v", err)
			}
		})
		t.Setenv("GIT_CEILING_DIRECTORIES", filepath.Dir(dir))

		got := run(t, "-changed")
		if got.code != 2 || got.stderr == "" {
			t.Fatalf("got %+v, want exit 2 with an error", got)
		}
	})
}
